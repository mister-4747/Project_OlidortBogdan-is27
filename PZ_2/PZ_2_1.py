# Практическое занятие № 2, Вариант 23.
# Задача: Дано целое число, большее 999. Используя одну операцию деления
# нацело и одну операцию взятия остатка от деления, найти цифру,
# соответствующую разряду тысяч в записи этого числа.


def get_thousands_digit() -> None:
    """Запрашивает целое число > 999 и выводит цифру разряда тысяч."""
    try:
        user_input = input("Введите целое число, большее 999: ")
        number = int(user_input)

        if number <= 999:
            print("Ошибка: число должно быть строго больше 999.")
            return

        # Одна операция деления нацело (//) и одна операция взятия остатка (%)
        thousands_digit = (number // 1000) % 10

        print(f"Цифра, соответствующая разряду тысяч: {thousands_digit}")

    except ValueError:
        print("Ошибка: введено не целое число. Пожалуйста, введите цифры.")


if __name__ == "__main__":
    get_thousands_digit()
